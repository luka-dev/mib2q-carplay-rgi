#!/usr/bin/env python3
"""Emit src/huff_tables.cpp from the committed reference dumps.

Nothing here is retyped by hand.  tools/apac_codebooks.py parses the codebook
structure out of reference/decomp/RODATA.md, cross-checks every field against
the library ELF and takes the payload bytes from the ELF, asserting they equal
the committed dumps in reference/decomp/rodata/ wherever one exists.  The
i^(4/3) and 2^(k/4) tables come from those dumps directly; the only bytes with
no dump at all are the 24 in front of 0x3308c0 (the negative wing of i^(4/3))
and one 4-byte guard payload, and both come from the ELF.

    apac_decoder/tools/gen_huff_tables.py [libSPF_CP_PlugInWrapper.so]
"""
import os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import apac_codebooks as CB

DEC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DEC, 'src', 'huff_tables.cpp')
LIB = sys.argv[1] if len(sys.argv) > 1 else CB.DEFAULT_LIB

books, missing = CB.load(LIB)
elf = CB.Elf(LIB)

lines = []
w = lines.append
w('// GENERATED by apac_decoder/tools/gen_huff_tables.py -- do not edit.')
w('//')
w('// Every byte below was copied out of the reference dumps in')
w('// reference/decomp/rodata/ or read straight out of')
w('// libSPF_CP_PlugInWrapper.so, and the two sources are asserted equal')
w('// wherever both exist.  Nothing here is retyped or recomputed: the i^(4/3)')
w('// table matches a generated one only to within 1 ULP.')
w('//')
w('// Structure: LRVQ_SEMANTICS.md section 1.1.  `n` caps the unary prefix, `a`')
w('// is a right shift giving 1 << (31 - a) uint16 payload slots, and each')
w('// payload word is (symbol << 6) | codewordLengthInBits.  entries[n] is a')
w('// real guard record carrying the all-ones code 1^n, with TWO slots.')
w('')
w('#include "apac/huffman.h"')
w('')
w('namespace apac {')
w('namespace {')
w('')

total = 0
for idx, b in enumerate(books):
    w('// ---- codebook %d: n = %d, descriptor 0x%08x, entries 0x%08x'
      % (idx, b['n'], b['desc'], b['entries']))
    for k, (a, p) in enumerate(b['pairs']):
        vals = b['payload'][k]
        total += len(vals)
        w('const uint16_t kCB%d_%d[%d] = {' % (idx, k, len(vals)))
        for i in range(0, len(vals), 12):
            w('    ' + ' '.join('0x%04x,' % v for v in vals[i:i + 12]))
        w('};')
    w('const HuffEntry kCB%dEntries[%d] = {' % (idx, len(b['pairs'])))
    for k, (a, p) in enumerate(b['pairs']):
        w('    { %2d, kCB%d_%d },   // 0x%08x, %d slots%s'
          % (a, idx, k, p, len(b['payload'][k]),
             '   <- guard, 1^%d' % b['n'] if k == b['n'] else ''))
    w('};')
    w('')

w('const HuffTable kTables[12] = {')
for idx, b in enumerate(books):
    w('    { kCB%dEntries, %2d },' % (idx, b['n']))
w('};')
w('')

# i^(4/3): six negative slots (0x3308a8..0x3308bf) then the 1024-entry dump.
neg = elf.read(0x3308a8, 24)
pos = CB.dump(0x3308c0)[:4096]
assert pos == elf.read(0x3308c0, 4096)
words = list(struct.unpack('<6I', neg)) + list(struct.unpack('<1024I', pos))
w('// i^(4/3), 0x003308c0, with the mirrored negative wing at X[-6..-1]')
w('// (0x003308a8: 0, 0, -4^(4/3), -3^(4/3), -2^(4/3), -1).  Books 1..6 index it')
w('// negatively, so the wing is part of the table, not slack.  Stored as bit')
w('// patterns because the values are NOT bit-exactly float(i ** (4.0 / 3.0)).')
w('const uint32_t kInvQuantBits[%d] = {' % len(words))
for i in range(0, len(words), 6):
    w('    ' + ' '.join('0x%08xu,' % v for v in words[i:i + 6]))
w('};')
w('')
q = CB.dump(0x310280)[:16]
assert q == elf.read(0x310280, 16)
w('// 2^(k/4) for k = 0..3, 0x00310280, used by the scalefactor exponent build.')
w('const uint32_t kTwoPowQuarterBits[4] = { %s };'
  % ' '.join('0x%08xu,' % v for v in struct.unpack('<4I', q)))
w('')
w('} // namespace')
w('')
w('const HuffTable* GetHuffmanTable(uint32_t n) { return &kTables[n]; }')
w('const HuffTable* GetSCFHuffmanTable()        { return &kTables[0]; }')
w('')
w('const float* const kInverseQuant =')
w('    reinterpret_cast<const float*>(kInvQuantBits) + kInverseQuantNegative;')
w('const float* const kTwoPowQuarter =')
w('    reinterpret_cast<const float*>(kTwoPowQuarterBits);')
w('')
w('} // namespace apac')

with open(OUT, 'w') as fh:
    fh.write('\n'.join(lines) + '\n')
sys.stderr.write('%s: %d payload slots, %d i^(4/3) entries, '
                 '%d payload(s) with no committed dump\n'
                 % (OUT, total, len(words), len(missing)))
