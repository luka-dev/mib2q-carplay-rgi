#!/usr/bin/env bash
#
# Regenerate the STAGE E (bandwidth extension) fixtures under
# apac_decoder/tests/fixtures/, from the real library.
#
#   apac_decoder/tools/gen_fixtures_bwe.sh
#
# Needs Docker: reference/apac_bwe_ref.cpp dlopens Pioneer's AArch64
# libSPF_CP_PlugInWrapper.so in a linux/arm64 container and calls BWELPC's and
# APACBWE2Decoder's members by their Itanium-mangled names.  `make check` does
# NOT need Docker - the fixtures are committed and the host tests replay them.
#
# Stage e has its own oracle source and its own generator so that it can be
# regenerated without touching reference/apac_fn_ref.cpp, which the other
# stages share.
#
# Every input is produced by reference/bwe_cases.h, which BOTH the oracle and
# tests/test_bwe.cpp include.  If that header changes, re-run this.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEC="$(cd "$HERE/.." && pwd)"
REF="$DEC/reference"
FIX="$DEC/tests/fixtures"
IMAGE="${APAC_IMAGE:-apac-ref}"
mkdir -p "$FIX"

# run.sh owns the library staging and the image build; borrow both.
"$REF/run.sh" fn probe >/dev/null

run() {
    docker run --rm --platform linux/arm64 -v "$REF:/src:ro" "$IMAGE" bash -c \
        'g++ -std=c++11 -O2 -g -Wall -Wextra -o /tmp/apac_bwe_ref /src/apac_bwe_ref.cpp -ldl \
         && exec /tmp/apac_bwe_ref "$@"' _ "$@"
}

emit() {
    local out="$FIX/$1"; shift
    echo "generating $(basename "$out")  ($*)"
    {
        echo "# GENERATED by apac_decoder/tools/gen_fixtures_bwe.sh"
        echo "# oracle: reference/apac_bwe_ref.cpp, command \`$1\`, running"
        echo "#         libSPF_CP_PlugInWrapper.so (Pioneer SPHERA 1.030010) natively"
        echo "#         on arm64.  Every number below is one the library produced."
        echo "# inputs: reference/bwe_cases.h - the host test regenerates them."
        echo "# floats are printed as their IEEE-754 bit pattern, big-endian hex."
        run "$@" 2>/dev/null
    } > "$out"
}

# BWELPC::DecodeLSFsToLPCs: the two-codebook LSF sum, Condition_LSFs,
# LSF_To_LSP and LSP_To_LPC, reported at all three intermediate stages.
emit bwe_lsf.fixture lsf

# BWELPC::LPCToMDCTSpectrum at all six BWELPC::kDftSizes plus two lengths the
# selector does not name.
emit bwe_env.fixture env

# BWELPC::MDCTCoefficientsToLPC on the frame cases' own spectra, long and
# eight-short.
emit bwe_lpc.fixture lpc

# APACBWE2Decoder::DecodeFrame end to end: the whole 1024-coefficient spectrum
# after the call, and the return value.
emit bwe_frame.fixture frame

echo "stage-e fixtures written to $FIX"
