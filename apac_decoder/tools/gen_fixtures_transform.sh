#!/usr/bin/env bash
#
# Regenerate the STAGE D (transform path) fixtures under
# apac_decoder/tests/fixtures/, from the real library.
#
#   apac_decoder/tools/gen_fixtures_transform.sh
#
# Needs Docker: the oracle dlopens Pioneer's AArch64
# libSPF_CP_PlugInWrapper.so in a linux/arm64 container and calls individual
# exported members by their Itanium-mangled names.  `make check` does NOT need
# Docker - the fixtures below are committed and the host tests replay them.
#
# Stage a and b have their own generator (tools/gen_fixtures.sh); this one is
# separate so the two can be regenerated independently.
#
# Every input vector is produced by reference/dsp_cases.h, which BOTH the oracle
# and the host tests include.  That is why the fixtures carry only the outputs:
# the inputs are 30 x 1024 floats for the filterbank alone and shipping them
# would bury the expectations.  If dsp_cases.h changes, re-run this.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEC="$(cd "$HERE/.." && pwd)"
FIX="$DEC/tests/fixtures"
RUN="$DEC/reference/run.sh"
mkdir -p "$FIX"

emit() {   # emit <fixture> <oracle command...>
    local out="$FIX/$1"; shift
    echo "generating $(basename "$out")  ($*)"
    {
        echo "# GENERATED by apac_decoder/tools/gen_fixtures_transform.sh"
        echo "# oracle: reference/apac_fn_ref.cpp, command \`$1\`, running"
        echo "#         libSPF_CP_PlugInWrapper.so (Pioneer SPHERA 1.030010) natively"
        echo "#         on arm64.  Every number below is one the library produced."
        echo "# inputs: reference/dsp_cases.h - the host test regenerates them."
        echo "# floats are printed as their IEEE-754 bit pattern, big-endian hex."
        "$RUN" fn "$@" 2>/dev/null
    } > "$out"
}

# GetSineWindowCoefficientPtr / GetKBDWindowCoefficientPtr /
# GetDCTIVModulationCoefficients: the NULL answers for every size that is not
# 128 or 1024, then all six tables word for word.
emit transform_tables.fixture win

# MDCT::Initialize + MDCT::InverseInPlaceTransform for both block sizes over
# every case in dsp_cases.h, both output halves.
emit mdct.fixture mdct

# APACSynthesisFilterBank::Initialize / Reset / FrequencyToTimeInPlace over the
# 30-step plan in dsp_cases.h: 3 channels, both window shapes, all four window
# sequences, plus the two rejection paths.
emit filterbank.fixture fb

# APACTNSData: the constructor's rate table over all 13 rates, then
# ParseTNSData + Apply over the 32-case plan in dsp_cases.h - both block
# layouts, and four cases the library rejects.
emit tns.fixture tns

echo "stage-d fixtures written to $FIX"
