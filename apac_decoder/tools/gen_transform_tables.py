#!/usr/bin/env python3
"""Emit src/transform_tables.cpp from the byte-for-byte .rodata dumps.

Every table in the transform path is COPIED out of the library, never generated.
Two of them look analytic and still are not reproducible bit-for-bit:

  * the sine windows match sinf(pi*(i+0.5)/2N) only to 7.3e-08;
  * the DCT-IV modulation table matches exp(i*pi*(m+1/8)/n) only to ~2e-08;
  * the KBD windows are not analytic at all (the Kaiser alpha was never solved).

So the float32 BIT PATTERN is what is stored here, as uint32, and the arrays are
unions so that `&t[0].f` is a plain `const float*` with the right stride.

Usage (from apac_decoder/):  python3 tools/gen_transform_tables.py
Inputs:  reference/decomp/rodata/apac_rodata_<addr>.bin
Output:  src/transform_tables.cpp
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RODATA = os.path.join(ROOT, 'reference', 'decomp', 'rodata')
OUT = os.path.join(ROOT, 'src', 'transform_tables.cpp')

# (C identifier, rodata address, float count, what it is)
TABLES = [
    ('kSineWindow128',  0x00345e00,  128,
     'rising half of the 256-point sine window; GetSineWindowCoefficientPtr(128)'),
    ('kSineWindow1024', 0x00347200, 1024,
     'rising half of the 2048-point sine window; GetSineWindowCoefficientPtr(1024)'),
    ('kKBDWindow128',   0x00346000,  128,
     'rising half of the 256-point Kaiser-Bessel-derived window; GetKBDWindowCoefficientPtr(128)'),
    ('kKBDWindow1024',  0x00346200, 1024,
     'rising half of the 2048-point KBD window; GetKBDWindowCoefficientPtr(1024)'),
    ('kDCTIVMod128',    0x00331d20,  128,
     'DCT-IV pre/post modulation, 64 interleaved (cos,sin) pairs; '
     'GetDCTIVModulationCoefficients(128)'),
    ('kDCTIVMod1024',   0x00331f20, 1024,
     'DCT-IV pre/post modulation, 512 interleaved (cos,sin) pairs; '
     'GetDCTIVModulationCoefficients(1024).  The dump is 4120 bytes; only the '
     'first 1024 floats belong to this table (RODATA.md, "extents are upper bounds")'),
    ('kTNSCoefficients', 0x003319d0,  32,
     'TNS parcor dequantisation, indexed by (coefRes << 4) | (coef + 8); '
     'read by APACTNSData::Apply'),
    ('kLPCLagWindow',   0x00332f80,   16,
     'autocorrelation lag window applied by apac::LPCBase::ComputeLPCs when its '
     '`bool` argument is set.  Entry 0 is never read - ComputeLPCs starts at '
     'index 1 and hardcodes 0.99941 for it'),
]


def main():
    parts = []
    parts.append('''// APAC transform-path constant tables - COPIED byte-for-byte out of
// libSPF_CP_PlugInWrapper.so (Pioneer SPHERA 1.030010, image base 0).
//
// GENERATED by tools/gen_transform_tables.py from
// reference/decomp/rodata/apac_rodata_<addr>.bin.  Do not edit by hand; edit
// the generator and re-run it from apac_decoder/:
//
//     python3 tools/gen_transform_tables.py
//
// Stored as float32 BIT PATTERNS, not as decimal literals, because none of
// these tables is reproducible from its closed form: the sine windows agree
// with sinf(pi*(i+0.5)/2N) only to 7.3e-08, the DCT-IV modulation table agrees
// with exp(i*pi*(m+1/8)/n) only to ~2e-08, and the KBD windows are not analytic
// at all.  tests/test_transform_tables.cpp checks every word against a fixture
// the library itself produced.

#include "apac/transform.h"

namespace apac {
namespace tables {
''')
    for name, addr, count, what in TABLES:
        path = os.path.join(RODATA, 'apac_rodata_%08x.bin' % addr)
        with open(path, 'rb') as fh:
            blob = fh.read()
        if len(blob) < count * 4:
            sys.exit('%s: %d bytes, need %d' % (path, len(blob), count * 4))
        words = struct.unpack('<%dI' % count, blob[:count * 4])
        parts.append('// 0x%08x, %d floats - %s\n' % (addr, count, what))
        parts.append('extern const F32 %s[%d] = {\n' % (name, count))
        for i in range(0, count, 6):
            row = ', '.join('{0x%08xu}' % w for w in words[i:i + 6])
            parts.append('    ' + row + ',\n')
        parts.append('};\n\n')
    parts.append('} // namespace tables\n} // namespace apac\n')
    with open(OUT, 'w') as fh:
        fh.write(''.join(parts))
    print('wrote %s' % OUT)


if __name__ == '__main__':
    main()
