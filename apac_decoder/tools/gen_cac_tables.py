#!/usr/bin/env python3
"""Emit src/cac_tables.cpp from the library ELF.  Nothing is retyped.

The two CAC variable-length code tables are static .rodata in
libSPF_CP_PlugInWrapper.so:

    CacDecoder::kGainIndexCodeTableDec  0x331b28  0xd2  bytes  35 records
    CacDecoder::kRepeatCodeTableDec     0x331c00  0x108 bytes  44 records

A record is six bytes: u8 value, u8 pad, u16 code, u8 length, u8 pad.  The
addresses and sizes are read out of the ELF's .dynsym, not hardcoded, and the
padding bytes are asserted zero.

    apac_decoder/tools/gen_cac_tables.py [libSPF_CP_PlugInWrapper.so]
"""
import os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import apac_codebooks as CB

DEC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DEC, 'src', 'cac_tables.cpp')
LIB = sys.argv[1] if len(sys.argv) > 1 else CB.DEFAULT_LIB


def dynsyms(elf):
    """{name: (value, size)} from .dynsym / .dynstr, via the section headers."""
    d = elf.d
    shoff, = struct.unpack_from('<Q', d, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 0x3a)
    secs = []
    for i in range(shnum):
        o = shoff + i * shentsize
        name, typ, _, addr, off, size, link, _, _, entsize = \
            struct.unpack_from('<IIQQQQIIQQ', d, o)
        secs.append(dict(name=name, typ=typ, off=off, size=size,
                         link=link, entsize=entsize))
    out = {}
    for s in secs:
        if s['typ'] != 11:          # SHT_DYNSYM
            continue
        strs = secs[s['link']]
        n = s['size'] // s['entsize']
        for i in range(n):
            o = s['off'] + i * s['entsize']
            nm, _, _, _, val, sz = struct.unpack_from('<IBBHQQ', d, o)
            end = d.index(b'\0', strs['off'] + nm)
            out[d[strs['off'] + nm:end].decode()] = (val, sz)
    return out


def records(elf, addr, size):
    raw = elf.read(addr, size)
    assert size % 6 == 0, size
    recs = []
    for i in range(0, size, 6):
        value, pad1, code, length, pad2 = struct.unpack_from('<BBHBB', raw, i)
        assert pad1 == 0 and pad2 == 0, (i, pad1, pad2)
        assert 1 <= length <= 16, (i, length)
        assert code < (1 << length), (i, code, length)
        recs.append((value, code, length))
    return recs


def main():
    elf = CB.Elf(LIB)
    syms = dynsyms(elf)
    tables = []
    for sym, cname, want in (
            ('_ZN10CacDecoder22kGainIndexCodeTableDecE', 'kCacGainCodeTable', 35),
            ('_ZN10CacDecoder19kRepeatCodeTableDecE', 'kCacRepeatCodeTable', 44)):
        addr, size = syms[sym]
        recs = records(elf, addr, size)
        assert len(recs) == want, (sym, len(recs))
        # A prefix code: no code may be a prefix of another.
        for i, (_, ci, li) in enumerate(recs):
            for j, (_, cj, lj) in enumerate(recs):
                if i == j or li > lj:
                    continue
                assert cj >> (lj - li) != ci, (sym, i, j)
        tables.append((sym, cname, addr, size, recs))

    w = []
    w.append('// GENERATED by apac_decoder/tools/gen_cac_tables.py -- do not edit.')
    w.append('//')
    w.append('// Both tables are copied byte for byte out of')
    w.append('// libSPF_CP_PlugInWrapper.so .rodata.  A record is six bytes:')
    w.append('// u8 value, u8 pad, u16 code, u8 length, u8 pad; the generator')
    w.append('// asserts the padding is zero, that every code fits its length,')
    w.append('// and that the set is prefix free.')
    w.append('')
    w.append('#include "apac/cac.h"')
    w.append('')
    w.append('namespace apac {')
    for sym, cname, addr, size, recs in tables:
        w.append('')
        w.append('// %s, 0x%08x, %d bytes' % (sym, addr, size))
        w.append('const CacCode %s[%d] = {' % (cname, len(recs)))
        for value, code, length in recs:
            w.append('    { %3d, 0x%04x, %2d },' % (value, code, length))
        w.append('};')
    w.append('')
    w.append('}  // namespace apac')
    w.append('')
    open(OUT, 'w').write('\n'.join(w))
    print('wrote %s: %d + %d records' % (OUT, len(tables[0][4]), len(tables[1][4])))


main()
