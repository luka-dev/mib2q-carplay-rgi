#!/usr/bin/env python3
"""Generate tests/escape_pow_table.h - the correctly-rounded float32 value of

    (float)pow((double)v, 4.0 / 3.0)

for every v codebook 11's escape can reach on the pow path, v in [1024, 8191].

The values are NOT taken from any libm.  They are the exact real number
v ** y, where y is the double 0x3FF5555555555555 (the double nearest 4/3, which
is what the library materialises), evaluated at 80 decimal digits with mpmath
and then rounded to float32.  That makes the table an implementation-independent
reference: it is what a correctly-rounded pow would give, so it is what QNX's
libm must give as well - see the margin printed at the end, which bounds how
wrong a pow may be before the float32 result would change.

    python3 tools/gen_escape_pow_table.py > tests/escape_pow_table.h
"""
import struct, sys
import mpmath as mp

mp.mp.dps = 80

YBITS = 0x3FF5555555555555
assert struct.unpack('<Q', struct.pack('<d', 4.0 / 3.0))[0] == YBITS
Y = mp.mpf(struct.unpack('<d', struct.pack('<Q', YBITS))[0])

VLO, VHI = 1024, 8191


def f32bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def bits2f32(b):
    return struct.unpack('<f', struct.pack('<I', b))[0]


rows = []
worst, worst_v = None, None
for v in range(VLO, VHI + 1):
    r = mp.power(mp.mpf(v), Y)
    b = f32bits(float(r))
    f = bits2f32(b)
    lo, hi = bits2f32(b - 1), bits2f32(b + 1)
    d = min(abs(r - (mp.mpf(lo) + mp.mpf(f)) / 2),
            abs(r - (mp.mpf(f) + mp.mpf(hi)) / 2))
    ulp = mp.mpf(2) ** (mp.frexp(r)[1] - 53)          # one double ULP at r
    m = d / ulp
    if worst is None or m < worst:
        worst, worst_v = m, v
    rows.append((v, b))

out = sys.stdout
out.write("// GENERATED by tools/gen_escape_pow_table.py - do not edit.\n")
out.write("//\n")
out.write("// (float)pow((double)v, 4.0/3.0) for v in [%d, %d], the whole domain\n" % (VLO, VHI))
out.write("// codebook 11's escape can drive onto the pow path.  Computed exactly\n")
out.write("// (mpmath, 80 digits) from y = 0x%016X, not read off any libm.\n" % YBITS)
out.write("//\n")
out.write("// Worst margin to a float32 rounding boundary: %.4g double-ULPs, at v=%d.\n"
          % (float(worst), worst_v))
out.write("// A pow wrong by less than that cannot change the float32 result, so every\n")
out.write("// libm within ~%d bits of correct agrees with this table.\n"
          % int(mp.floor(mp.log(worst, 2))))
out.write("#ifndef APAC_ESCAPE_POW_TABLE_H\n#define APAC_ESCAPE_POW_TABLE_H\n\n")
out.write("#include <stdint.h>\n\n")
out.write("static const uint32_t kEscapePowLo = %d;\n" % VLO)
out.write("static const uint32_t kEscapePowHi = %d;\n\n" % VHI)
out.write("static const uint32_t kEscapePowBits[%d] = {\n" % len(rows))
for i in range(0, len(rows), 8):
    out.write("    " + " ".join("0x%08x," % b for _, b in rows[i:i + 8]) + "\n")
out.write("};\n\n#endif\n")
sys.stderr.write("worst float32 rounding margin %.4g double-ULPs at v=%d\n" % (float(worst), worst_v))
