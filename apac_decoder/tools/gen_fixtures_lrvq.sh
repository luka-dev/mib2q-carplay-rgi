#!/usr/bin/env bash
#
# Regenerate the STAGE H1 (LRVQ) fixtures under apac_decoder/tests/fixtures/,
# from the real library.
#
#   apac_decoder/tools/gen_fixtures_lrvq.sh
#
# Needs Docker: reference/apac_lrvq_ref.cpp dlopens Pioneer's AArch64
# libSPF_CP_PlugInWrapper.so in a linux/arm64 container and calls
# APACLRVQDecoder's members by their Itanium-mangled names.  `make check` does
# NOT need Docker - the fixtures are committed and the host tests replay them.
#
# Stage h1 has its own oracle source and its own generator so that it can be
# regenerated without touching reference/apac_fn_ref.cpp, which the other
# stages share.
#
# Every input is produced by reference/lrvq_cases.h, which BOTH the oracle and
# tests/test_lrvq.cpp include.  If that header changes, re-run this.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEC="$(cd "$HERE/.." && pwd)"
REF="$DEC/reference"
FIX="$DEC/tests/fixtures"
IMAGE="${APAC_IMAGE:-apac-ref}"
mkdir -p "$FIX"

# run.sh owns the library staging and the image build; borrow both.
"$REF/run.sh" fn probe >/dev/null

run() {
    docker run --rm --platform linux/arm64 -v "$REF:/src:ro" "$IMAGE" bash -c \
        'g++ -std=c++11 -O2 -g -Wall -Wextra -o /tmp/apac_lrvq_ref /src/apac_lrvq_ref.cpp -ldl \
         && exec /tmp/apac_lrvq_ref "$@"' _ "$@"
}

emit() {
    local out="$FIX/$1"; shift
    echo "generating $(basename "$out")  ($*)"
    {
        echo "# GENERATED by apac_decoder/tools/gen_fixtures_lrvq.sh"
        echo "# oracle: reference/apac_lrvq_ref.cpp, command \`$1\`, running"
        echo "#         libSPF_CP_PlugInWrapper.so (Pioneer SPHERA 1.030010) natively"
        echo "#         on arm64.  Every number below is one the library produced."
        echo "# inputs: reference/lrvq_cases.h - the host test regenerates them."
        echo "# floats are printed as their IEEE-754 bit pattern, big-endian hex."
        run "$@" 2>/dev/null
    } > "$out"
}

# APACLRVQDecoder::dequantizeLrvqGain, all 512 indices x both gain modes.
emit lrvq_gain.fixture gain

# APACLRVQDecoder::ltpToMdctSpectralEnvelope, 96 (gainIndex, lag) pairs
# including lag 0, which overwrites the impulse's leading 1.0.
emit lrvq_ltp.fixture ltp

# apac::LSFTools::LSF_To_LPC on the same 64 index sets - the LSF half of
# lsfsToMdctSpectralEnvelope on its own, so a disagreement can be attributed to
# the LPC chain or to the FFT and not to "somewhere in there".
emit lrvq_lsf2lpc.fixture lsf2lpc

# APACLRVQDecoder::lsfsToMdctSpectralEnvelope, 64 index sets over both codebook
# sets - the LSF -> LPC -> 512-point FFT chain that had never been driven.
emit lrvq_lsfs.fixture lsfs

# APACLRVQDecoder::LrvqDeserialize over the whole case plan: return value, bits
# consumed, prevMode, qidx, work, env and the 1024-coefficient spectrum.
emit lrvq_frame.fixture lrvq

# APACChannelPairElement::DeserializeLrvqFrame on a hand-built element: the two
# ICS headers, the CPE spectrum, both TNS blocks and the extra bit between them.
emit lrvq_cpe_frame.fixture frame

# SpectrumDeserializeSCE / CPE / LFE - the element wrappers and their skip bit.
emit lrvq_elem.fixture elem

echo "stage-h1 fixtures written to $FIX"
