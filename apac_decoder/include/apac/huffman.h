// The APAC Huffman codebooks: one scalefactor book and eleven spectral books.
//
// Original: apac::GetHuffmanTable(uint32) at 0x00099dc0 is `return
// off_424D98[n]` over a 12-entry pointer array, and apac::GetSCFHuffmanTable()
// at 0x00099e10 returns entry 0 - so codebook 0 IS the scalefactor book.
//
// The code is a unary-prefix code, not a canonical Huffman code, and the two
// descriptor fields are not what their sizes suggest.  From
// reference/decomp/LRVQ_SEMANTICS.md section 1.1, established against the
// running library:
//
//   * `n` caps the unary prefix.  Both decoders build a clamp from it and take
//     clz(clamp | ~w), which is min(leadingOnes(w), n).  APACScaleFactorData
//     spells the clamp 0x80000000u >> n and APACSpectralData spells it
//     (1u << (32 - n)) - 1; the two constants have the same clz.
//   * `a` is a RIGHT SHIFT.  entries[k] owns prefix length k and its payload
//     has exactly 1 << (31 - a) uint16 slots, indexed by (w << k) >> a.
//   * a payload word is (symbol << 6) | codewordLengthInBits, the length
//     counting the k prefix ones and the terminating zero.
//   * entries[n] is a real, in-bounds guard record carrying the single
//     all-ones code 1^n.  Counting it, every book's Kraft sum is exactly 1.
//     It is the one record whose payload is NOT 1 << (31 - a) slots: having no
//     terminating zero, its index (w << n) >> 31 is the bit after the n ones,
//     which belongs to the next codeword and can be either value, so the
//     binary gives it TWO slots holding the same word.  Sizing it at one, as
//     the formula would, reads two bytes past the table.
//
// The symbol layout inside the top ten bits differs per codebook family; that
// lives in the decoders, not here.
//
// Tables are generated by tools/gen_huff_tables.py into src/huff_tables.cpp.

#ifndef APAC_HUFFMAN_H
#define APAC_HUFFMAN_H

#include <stdint.h>

namespace apac {

struct HuffEntry {
    uint32_t        shift;      // `a`: index = (uint32_t)(w << k) >> shift
    const uint16_t* payload;    // 1 << (31 - shift) entries
};

struct HuffTable {
    const HuffEntry* entries;   // n + 1 records: n usable plus the guard
    uint32_t         n;
};

// n must be 0..11.  0 is the scalefactor book.
const HuffTable* GetHuffmanTable(uint32_t n);
const HuffTable* GetSCFHuffmanTable();

// The inverse-quantisation table, i^(4/3) at 0x003308c0, biased so that
// kInverseQuant[-4 .. 1023] is addressable: codebooks 1..6 index it with
// negative values and the library's table has a mirrored negative wing in
// front of it.  Copied byte-for-byte - a generated table differs by up to 1
// ULP, which is not bit-exact.
const int32_t kInverseQuantNegative = 6;   // slots in front of index 0
const uint32_t kInverseQuantMax     = 1023;
extern const float* const kInverseQuant;

// 2^(k/4), k = 0..3, at 0x00310280.
extern const float* const kTwoPowQuarter;

} // namespace apac

#endif
