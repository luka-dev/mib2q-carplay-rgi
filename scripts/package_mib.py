#!/usr/bin/env python3
"""Prepare release artifacts in build/ and two M.I.B. folders. No ZIP or HU access."""
import argparse
import difflib
import hashlib
import json
from pathlib import Path
import shutil
import struct
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "install_MoreIncredibleBash"
UNINSTALL = ROOT / "uninstall_MoreIncredibleBash"
NATIVE = ("libcarplay_hook.so", "libcarplay_apac.so", "maneuver_render", "altscreen_render")
RUNTIME = ("carplay_startup.sh", "carplay_monitor.sh", "carplay_processes.sh", "carplay_cleanup.sh")
FIRMWARE = {
    "smartphone_integrator": "606236a81c7c4dafda6fdd08fe6eb27c43252796784da25d9760a7d552ee2af3",
    "deva-ctrl-qc.so": "398e7213be4e966719eed5ff9736fb9142f11e161033f01263f29db640e06355",
}
BINARIES = (*NATIVE, *RUNTIME, "hssr_model.bin", "hssr_guard.bin", "flag_atlas.rgba", "carplay_hook.jar", *FIRMWARE)
FILES = ("../mod/custom.sh", "release.json", "carplay_child.json", "carplay_pf.patch",
         "patch_si_rearm.py", *BINARIES)
# Main control model = q6d (MoisesDB real classes, fine-tuned from V11); guard = V11 vocal safety net.
MODEL_SHA = "96abe57d9ee703f2e39c0231de97580c303ce896ce044b7450c14240002b0a0e"
GUARD_SHA = "ab01463e9359f013c4b40f311d630bd20af48d761ad361563cb5246f6bd686ae"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cksum(path):
    # POSIX CRC + length, identical on the host and stock QNX cksum.
    result = subprocess.check_output(["cksum"], input=path.read_bytes()).decode().split()
    if len(result) != 2:
        raise ValueError("unsupported host cksum")
    return " ".join(result)


def validate_bin(folder):
    for name in BINARIES:
        if not (folder / name).is_file() or (folder / name).stat().st_size == 0:
            raise ValueError(f"missing/empty {name}")
    for name in NATIVE:
        data = (folder / name).read_bytes()
        if (data[:6] != b"\x7fELF\x01\x01" or len(data) < 52
                or struct.unpack_from("<H", data, 18)[0] != 40
                or struct.unpack_from("<H", data, 16)[0] not in (2, 3)):
            raise ValueError(f"not an ARM32 little-endian ELF: {name}")
    for name, expected in FIRMWARE.items():
        if sha(folder / name) != expected:
            raise ValueError(f"not the verified final MU1316 firmware image: {name}")
    if sha(folder / "hssr_model.bin") != MODEL_SHA:
        raise ValueError("not the selected shipping HSSR q6d model")
    if sha(folder / "hssr_guard.bin") != GUARD_SHA:
        raise ValueError("not the V11 guard model")
    with zipfile.ZipFile(folder / "carplay_hook.jar") as jar:
        if jar.testzip():
            raise ValueError("JAR CRC failure")
        classes = [n for n in jar.namelist() if n.endswith(".class")]
        if not classes:
            raise ValueError("empty JAR")
        for name in classes:
            data = jar.read(name)
            if data[:4] != b"\xca\xfe\xba\xbe" or struct.unpack_from(">H", data, 6)[0] > 48:
                raise ValueError(f"incompatible J9 class: {name}")
        for resource in (ROOT / "java_resources").rglob("*"):
            if resource.is_file():
                name = resource.relative_to(ROOT / "java_resources").as_posix()
                if jar.read(name) != resource.read_bytes():
                    raise ValueError(f"missing/stale embedded resource: {name}")
    for name in RUNTIME:
        subprocess.run(["sh", "-n", str(folder / name)], check=True)


def uninstall_script():
    source = (PACKAGE / "mod/custom.sh").read_text()
    marker = 'ACTION=${1:-install}'
    if source.count(marker) != 1:
        raise ValueError("installer default-action marker changed")
    return source.replace(marker, 'ACTION=${1:-uninstall}').replace(
        '# M.I.B. SD1:', '# Generated by scripts/package_mib.py from the install script.\n# M.I.B. SD1:', 1)


def check_uninstall(folder=UNINSTALL):
    script = folder / "mod/custom.sh"
    if script.read_text() != uninstall_script():
        raise ValueError("uninstall script is stale; run scripts/package_mib.py")
    subprocess.run(["sh", "-n", str(script)], check=True)
    print(f"Standalone uninstall verified: {folder}")


def artifact_path(folder, name):
    return PACKAGE / "mod/custom.sh" if name == "../mod/custom.sh" else folder / name


def check(folder):
    lines = (folder / "SHA256SUMS").read_text().splitlines()
    if any(len(line.split()) != 2 for line in lines):
        raise ValueError("malformed SHA256SUMS")
    expected = {line.split()[1]: line.split()[0] for line in lines}
    if len(lines) != len(FILES) or set(expected) != set(FILES):
        raise ValueError("unexpected/missing SHA256SUMS entries")
    for name in FILES:
        if sha(artifact_path(folder, name)) != expected[name]:
            raise ValueError(f"SHA-256 mismatch: {name}; prepare the artifacts again")
    checksums = "".join(f"{cksum(artifact_path(folder, name))} {name}\n" for name in FILES)
    if (folder / "CKSUMS").read_text() != checksums:
        raise ValueError("CKSUMS mismatch")
    validate_bin(folder)
    subprocess.run(["sh", "-n", str(PACKAGE / "mod/custom.sh")], check=True)
    release = json.loads((folder / "release.json").read_text())
    for name, digest in release["sha256"].items():
        if sha(artifact_path(folder, name)) != digest:
            raise ValueError(f"release receipt mismatch: {name}")
    print(f"Release artifacts verified: {folder}")


def build(args):
    folder = args.build_dir
    # Existing compiled outputs are read only. Add the runtime/configuration
    # copies needed by the future release; never rebuild or replace the ELFs/JAR.
    for name in (*NATIVE, "carplay_hook.jar"):
        if not (folder / name).is_file():
            raise ValueError(f"missing compiled artifact: {folder / name}")
    sources = {name: ROOT / "deploy/smartphone_integrator" / name for name in RUNTIME}
    sources.update({
        "hssr_model.bin": ROOT / "build/hssr-q6d-moises-a/hssr_model.bin",
        "hssr_guard.bin": ROOT / "build/hssr-selection-v11/hssr_model.bin",
        "flag_atlas.rgba": ROOT / "maneuver_render/resources/flag_atlas.rgba",
        "smartphone_integrator": ROOT / "deploy/usb_replug_recovery/bundle_mu1316_p5087/payload/smartphone_integrator",
        "deva-ctrl-qc.so": ROOT / "deploy/deva-ctrl-qc/deva-ctrl-qc-mirror.so",
        "patch_si_rearm.py": ROOT / "deploy/usb_replug_recovery/patch_si_rearm.py",
    })
    for name, source in sources.items():
        shutil.copy2(source, folder / name)
    # Keep the fragment's closing brace on the SI child's original comma line.
    child = (ROOT / "deploy/smartphone_integrator/carplay_child.json").read_bytes().rstrip()
    (folder / "carplay_child.json").write_bytes(child)
    patch = []
    for name in ("pf.conf", "pf.ecm0.conf", "pf.mlan0.conf", "pf.ppp0.conf"):
        old = (ROOT / "deploy/smartphone_integrator/pf_stock" / name).read_text()
        new = []
        hits = 0
        for line in old.splitlines(keepends=True):
            if line.startswith('pass in quick on carplay0 proto tcp from any to any port {'):
                hits += line.count(' 6030,')
                line = line.replace(' 6030,', ' 6030:6032,')
            new.append(line)
        if hits != 1:
            raise ValueError(f"unsupported stock PF profile: {name}")
        patch.extend(difflib.unified_diff(old.splitlines(keepends=True), new,
                                        fromfile=f"a/etc/{name}", tofile=f"b/etc/{name}"))
    (folder / "carplay_pf.patch").write_text("".join(patch))
    validate_bin(folder)
    receipt = json.loads((folder / "carplay_hook-build.json").read_text())
    if receipt["sha256"] != sha(folder / "carplay_hook.jar"):
        raise ValueError("Java build receipt does not match the JAR")
    release = {
        "target": "MHI2Q_US_AUG22_P5087_MU1316", "deployed": False,
        "java": {key: value for key, value in receipt.items() if key != "jar"},
        "native": {"source": "existing build outputs, preserved without rebuilding",
                   "sha256": {name: sha(folder / name) for name in NATIVE}},
        "sha256": {name: sha(artifact_path(folder, name)) for name in FILES if name != "release.json"},
    }
    (folder / "release.json").write_text(json.dumps(release, indent=2) + "\n")
    (folder / "CKSUMS").write_text("".join(f"{cksum(artifact_path(folder, n))} {n}\n" for n in FILES))
    (folder / "SHA256SUMS").write_text("".join(f"{sha(artifact_path(folder, n))}  {n}\n" for n in FILES))
    (UNINSTALL / "mod").mkdir(parents=True, exist_ok=True)
    (UNINSTALL / "mod/custom.sh").write_text(uninstall_script())
    (UNINSTALL / "mod/custom.sh").chmod(0o755)
    shutil.copy2(ROOT / "docs/RELEASE_ARTIFACTS.md", folder / "README_CARPLAY_BUILD.md")
    check(folder)
    check_uninstall()
    print("Prepared two M.I.B. folders and loose build artifacts. No archive created.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--uninstall", action="store_true", help="only verify the standalone uninstall folder")
    args = parser.parse_args()
    try:
        if args.uninstall:
            check_uninstall()
        elif args.check:
            check(args.build_dir)
            check_uninstall()
        else:
            build(args)
    except (ValueError, OSError, KeyError, zipfile.BadZipFile, subprocess.CalledProcessError) as exc:
        parser.exit(1, f"FAILED: {exc}\n")


if __name__ == "__main__":
    main()
