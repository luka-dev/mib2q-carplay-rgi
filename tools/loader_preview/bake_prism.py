#!/usr/bin/env python3
"""Bake selected PRISM resources; generated headers are sufficient to compile."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

HERE=Path(__file__).resolve().parent
COMMON=HERE.parents[1]/'common'

def image(name,path):
    data=path.read_bytes()
    with Image.open(path) as im: w,h=im.size
    rows=['    '+','.join(f'0x{v:02x}' for v in data[i:i+20])+',' for i in range(0,len(data),20)]
    return (f'#define {name}_W {w}\n#define {name}_H {h}\n'
            f'/* PNG sha256: {hashlib.sha256(data).hexdigest()} */\n'
            f'static const unsigned char {name}_PNG[]={{\n'+'\n'.join(rows)+'\n};\n')

def string(name,source):
    return f'static const char {name}[]=\n'+''.join(json.dumps(line)+'\n' for line in source.splitlines(True))+';\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    shader=(HERE/'prism.frag').read_text()
    desktop='#version 120\n'+shader
    gles='#version 100\nprecision highp float;\n'+shader
    baked='/* Generated by tools/loader_preview/bake_prism.py. Do not edit. */\n#ifndef PRISM_BAKED_H\n#define PRISM_BAKED_H\n'
    baked+=image('PRISM_MATERIAL',HERE/'logo_material.png')
    baked+=image('PRISM_SIGNATURE',HERE/'sig_prism_soft.png')
    baked+=string('PRISM_FRAGMENT_DESKTOP',desktop)+string('PRISM_FRAGMENT_GLES',gles)+'#endif\n'
    demo='/* Test fixture only: never included by the vehicle renderer. */\n#ifndef PRISM_DEMO_BAKED_H\n#define PRISM_DEMO_BAKED_H\n'
    demo+=image('PRISM_DEMO',HERE/'stream_demo.png')+'#endif\n'
    for path,text in [(COMMON/'prism_baked.h',baked),(HERE/'prism_demo_baked.h',demo)]:
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit(f'Stale baked header: {path}')
        else: path.write_text(text)
        print(('Verified ' if args.check else 'Baked ')+str(path))

if __name__=='__main__':main()
