/*
 * AltScreenModule — cluster (LVDS2 / terminal 1) CONTEXT MANAGER.
 *
 * TWO custom contexts: dc[81] = {99} is the plain CarPlay cluster map and dc[80] adds the
 * maneuver popup/backing planes {98,101,102}.  Every new CarPlay session starts in 81.  Context
 * 80 is permitted only after RouteGuidance has published its current RGI state through BAP and
 * maneuver_render has confirmed a rendered frame.  Disconnect restores stock context 74.
 *
 * The CarPlay supervisor keeps both renderers alive for the dio_manager generation, so windows
 * 98/99 exist throughout the session. The only connected-session transition is 81 -> 80 after
 * RGI presentation confirmation, and 80 -> 81 after a bounded KDK-removal hold when
 * guidance/presentation goes away.
 *
 * The context table itself (dc[80]) is declared to the native compositor at init via
 * DisplayManager.declareContexts(dc); getMappedInternalContext is identity on MIB2High, so
 * switchContext(80) lands on exactly that declared context.
 *
 * There is exactly ONE persistent worker for the module lifetime and it is the SOLE caller of
 * DisplayManager.switchContext/setUpdateRate.  Single writer => two switches can never race the
 * bounce+settle, and no stale per-session worker can exist.  start()/stop() only publish the
 * desired context; the worker converges the cluster to it.
 */
package com.luka.carplay.core;

import com.luka.carplay.bus.CarplayBus;
import com.luka.carplay.framework.Log;

import de.audi.atip.hmi.view.IDisplayManager;
import de.audi.atip.start.ILastmodeStorage;
import de.audi.tghu.fwhmi.IDisplayManagerKombiControl;

public final class AltScreenModule implements Module, CarplayBus.Listener {

    private static final String TAG = "AltScreen";

    public static final int TERMINAL_CLUSTER  = 1;    /* LVDS2 */
    /* The single CarPlay cluster context: dc[80] = {98 popup, 102/101 KDK bg, 99 CarPlay video}.
     * If on-unit displayable 99 fails to composite, flip this to a video-less sibling as a
     * calibration knob (e.g. a dc[] slot that carries {98,102,101,33} over the stock map). */
    public static final int CTX_CLUSTER       = 80;   /* nav active: {98 maneuver, 101/102 backing, 99 map} */
    public static final int CTX_CLUSTER_MAP   = 81;   /* no nav: {99 map} only (no backing box, no maneuver) */
    public static final int CTX_STOCK_CLUSTER = 74;
    private static final int CTX_BOUNCE       = 72;   /* kombi map — never ours; forces a real ctx change */
    private static final int BOUNCE_SLEEP_MS  = 180;  /* preContextSwitchHook settle (proven driver) */
    /* VC drives KDK removal through an asynchronous fade-out completion callback.  That callback is
     * not exposed to the HU Java process, so keep ctx 80 composed for one bounded fallback interval
     * before dropping the maneuver/backing planes.  Never sleep on the HMI/BAP caller thread. */
    private static final long NAV_HIDE_HOLD_MS = 250L;
    private static final long CONTEXT_RECONCILE_MS = 250L;
    private static final int CLUSTER_FPS      = 30;   /* cluster encoder rate; MOST/encoder may cap below this */
    private static final int KOMBI_TYPE_G24   = 4;
    public static final int VIEWAREA_FULLSCREEN = 0;
    public static final int VIEWAREA_SMALLSCREEN = 1;
    private static final int VIEWAREA_SPORTSCREEN = 1;
    private static final int VIEWAREA_CLASSICSCREEN = 2;
    private static final int VIEWAREA_ANIMATION_MS = 250;

    /** Lightweight notification for consumers whose cluster presentation differs by view area. */
    public interface ViewAreaModeListener {
        void onViewAreaModeChanged(int mode);
    }

    /** Route-info toggle seam driven by the raw MFW left-roller press listener. */
    public interface InfoModeListener {
        void onInfoModeToggle();
    }

    private static final Object LOCK = new Object();
    private IDisplayManager dm;                  /* current DisplayManager (guarded by LOCK); stable across sessions */
    private Thread worker;                        /* the ONE persistent switch worker (guarded by LOCK) */
    private static volatile Thread contextWriterThread;

    /* true while the cluster is on OUR context (set AFTER the physical switch completes). */
    private static volatile boolean clusterActive = false;
    private static volatile boolean platformSupported = true;
    private boolean enabled;
    public static boolean isClusterActive() { return clusterActive; }

    /**
     * Consume the instrument-cluster MapScale step generated by the steering-wheel
     * roller.  This is deliberately NOT TerminalMode.updateRotary(): that callback
     * belongs to the centre-console MMI encoder and must continue controlling the
     * main CarPlay screen.
     *
     * MapScale.steps is a signed BAP byte. The hook converts its sign into the
     * UUID-addressed CarPlay changeMapZoomLevel command, so the cluster scene is
     * targeted directly and the main CarPlay UI does not move.
     * Consume from the ownership-intent edge, before the asynchronous DisplayManager
     * switch completes.  Waiting for clusterActive leaves a SETUP/bounce window in
     * which the request reaches the hidden Audi map and can restart its map-ready
     * lifecycle.  Once CarPlay intends to own terminal 1 we always consume the event,
     * even if the bus is momentarily reconnecting.
     */
    public static boolean consumeSteeringWheelScale(int steps) {
        if (!isConnected()) return false;

        if (steps != 0) {
            if (steps > 127) steps = 127;
            else if (steps < -127) steps = -127;
            byte[] payload = new byte[]{ (byte) steps };
            boolean ok = CarplayBus.getInstance().sendBinary(CarplayBus.CMD_ALT_ZOOM, payload);
            Log.i(TAG, "MFL roller -> altScreen zoom step=" + steps + " queued=" + ok);
        }
        return true;
    }

    /* true from start() (BEFORE any switch) until stop() — i.e. we intend to own the cluster this whole
     * session.  The switchToTargetContext View-pin reads THIS, not clusterActive: pinning on the
     * applied state leaves a ~180ms window during the first switch where a View press could steal
     * terminal 1 to the stock map (worker then thinks it still owns ctx → stuck).  Intent-based pin
     * closes that window from t0. */
    public static boolean isConnected() { return platformSupported && (connected || videoAvailable); }

    /** DisplayManagerMIB2High uses this to distinguish our serialized 72/80/81/74
     * writes from stock screen-controller requests while CarPlay owns terminal 1. */
    public static boolean isClusterContextWriterThread() {
        return Thread.currentThread() == contextWriterThread;
    }

    static boolean isPlatformSupported(FrameworkRef fw) {
        try { return fw != null && fw.framework() != null
            && fw.framework().getKombiType() != KOMBI_TYPE_G24; }
        catch (Throwable t) { return true; }  /* only an explicit G24 value disables the feature */
    }

    /* desiredCtx = target published by start()/stop(); currentCtx = what the worker last applied.
     * Both guarded by LOCK; the single worker switches whenever they differ, converging to desiredCtx. */
    private static int desiredCtx = CTX_STOCK_CLUSTER;
    private static int currentCtx = -1;
    /* desiredCtx is a pure function of these two (guarded by LOCK):
     *   !connected           -> 74 (stock)
     *   connected, no nav    -> 81 (map only)
     *   connected, nav       -> 80 (map + backing + maneuver) */
    private static volatile boolean connected = false;
    /* The renderer's VIDEO_ON event is the data-plane truth.  TMDev can briefly
     * publish INVALID during a dio bounce even though the re-established 111
     * stream is already decoding; without this fallback the module remains on
     * stock ctx 74 while displayable 99 renders invisibly. */
    private static volatile boolean videoAvailable = false;
    private static volatile boolean navActive = false;
    private static boolean navHidePending;
    private static int navHideGeneration;
    private static volatile boolean acceptVideoFallback = false;
    private static int lifecycleGeneration;
    private static final long VIDEO_FALLBACK_GRACE_MS = 1500L;
    /* Desired Audi View-button state. The C hook also caches this before the
     * RTSP altScreen session exists and applies it on the first decoded IDR. */
    private static int desiredViewAreaMode = VIEWAREA_FULLSCREEN;
    /* Stock MIB2High's actual visual skin, not DSICarKombi's display-preset
     * semantic.  DisplayManagerEvo treats LastmodeStorage skin 1 as Sport and
     * all normal skin-0 operation as Classic.  Unknown falls back to Sport
     * geometry until the stock store becomes available. */
    private static int clusterStyle = AltscreenControlServer.STYLE_UNKNOWN;
    private static volatile ILastmodeStorage layoutStorage;
    private static volatile ViewAreaModeListener viewAreaModeListener;
    private static volatile InfoModeListener infoModeListener;

    public static boolean isSmallScreenViewArea() {
        synchronized (LOCK) { return desiredViewAreaMode == VIEWAREA_SMALLSCREEN; }
    }

    public static void setViewAreaModeListener(ViewAreaModeListener listener) {
        viewAreaModeListener = listener;
    }

    public static void clearViewAreaModeListener(ViewAreaModeListener listener) {
        if (viewAreaModeListener == listener) viewAreaModeListener = null;
    }

    public static void setInfoModeListener(InfoModeListener listener) {
        infoModeListener = listener;
    }

    public static void clearInfoModeListener(InfoModeListener listener) {
        if (infoModeListener == listener) infoModeListener = null;
    }

    /** Raw DSI key 40 (left steering-wheel roller), never the centre-console DDS.
     *  SteeringWheelInputModule already gates this callback to the confirmed
     *  VC map tab. Route-info is meaningful only with an active RGI snapshot. */
    public static void onSteeringWheelOkPressed() {
        if (!isConnected() || !isNavActive()) {
            Log.d(TAG, "MFW OK ignored: no active RGI presentation");
            return;
        }
        InfoModeListener listener = infoModeListener;
        if (listener == null) {
            Log.d(TAG, "MFW OK ignored: RGI listener not ready");
            return;
        }
        listener.onInfoModeToggle();
    }

    private static boolean sendViewAreaMode(String reason) {
        int mode;
        synchronized (LOCK) { mode = effectiveViewAreaModeLocked(); }
        byte[] payload = new byte[3];
        payload[0] = (byte) mode;
        payload[1] = (byte) (VIEWAREA_ANIMATION_MS & 0xff);
        payload[2] = (byte) ((VIEWAREA_ANIMATION_MS >>> 8) & 0xff);
        boolean ok = CarplayBus.getInstance().sendBinary(CarplayBus.CMD_ALT_ZONE, payload);
        Log.i(TAG, "viewArea send mode=" + viewAreaName(mode)
            + " reason=" + reason + " queued=" + ok);
        return ok;
    }

    /** Called by the stock NAV_VIEW_SIZE_CHOICE model: value 0=fullscreen, value 1=smallscreen. */
    public static void setViewAreaMode(int mode) {
        mode = (mode == VIEWAREA_SMALLSCREEN) ? VIEWAREA_SMALLSCREEN : VIEWAREA_FULLSCREEN;
        /* Renderer starts before RTSP 111 and needs the mode independently of
         * the hook so its loader uses the correct physical safe area. */
        AltscreenControlServer.setViewAreaMode(mode);
        synchronized (LOCK) {
            if (desiredViewAreaMode == mode) return;
            desiredViewAreaMode = mode;
        }
        sendViewAreaMode("NAV_VIEW_SIZE_CHOICE");
        ViewAreaModeListener listener = viewAreaModeListener;
        if (listener != null) {
            try { listener.onViewAreaModeChanged(mode); }
            catch (Throwable t) { Log.w(TAG, "viewArea listener failed: " + t); }
        }
    }

    /** Refresh from the same stock value DisplayManagerEvo uses to choose its
     * Classic/Sport KDK assets.  Called on module start and by the existing
     * 250-ms connected-context reconcile worker, so a live skin switch is
     * reflected without another DSI activator or classpath override. */
    private static void refreshClusterStyleFromStock(String reason) {
        ILastmodeStorage storage = layoutStorage;
        if (storage == null) return;
        int skin;
        try { skin = storage.getSkin(); }
        catch (Throwable t) {
            Log.d(TAG, "VC skin read failed: " + t);
            return;
        }
        int style;
        if (skin == 1) style = AltscreenControlServer.STYLE_SPORT;
        else if (skin == 0) style = AltscreenControlServer.STYLE_CLASSIC;
        else {
            Log.w(TAG, "unknown stock VC skin=" + skin + "; preserving geometry");
            return;
        }
        boolean resend;
        synchronized (LOCK) {
            resend = clusterStyle != style &&
                desiredViewAreaMode == VIEWAREA_SMALLSCREEN;
            if (clusterStyle == style) return;
            clusterStyle = style;
        }
        AltscreenControlServer.setClusterStyle(style, skin);
        Log.i(TAG, "VC style="
            + (style == AltscreenControlServer.STYLE_CLASSIC ? "classic" : "sport")
            + " stockSkin=" + skin + " reason=" + reason
            + " resendCompact=" + resend);
        if (resend) sendViewAreaMode("VC_SKIN_CHANGE");
    }

    /* Caller holds LOCK. */
    private static int effectiveViewAreaModeLocked() {
        if (desiredViewAreaMode != VIEWAREA_SMALLSCREEN)
            return VIEWAREA_FULLSCREEN;
        return clusterStyle == AltscreenControlServer.STYLE_CLASSIC
            ? VIEWAREA_CLASSICSCREEN : VIEWAREA_SPORTSCREEN;
    }

    private static String viewAreaName(int mode) {
        if (mode == VIEWAREA_SPORTSCREEN) return "sportscreen";
        if (mode == VIEWAREA_CLASSICSCREEN) return "classicscreen";
        return "fullscreen";
    }

    public void onFrame(int type, int flags, byte[] payload, int len) {
        if (type == CarplayBus.EVT_HELLO) {
            sendViewAreaMode("hook-hello");
        } else if (type == CarplayBus.CMD_ALT_ZONE_ACK && payload != null && len >= 5) {
            int mode = payload[0] & 0xff;
            int status = (payload[1] & 0xff)
                       | ((payload[2] & 0xff) << 8)
                       | ((payload[3] & 0xff) << 16)
                       | ((payload[4] & 0xff) << 24);
            Log.i(TAG, "viewArea ack mode=" + viewAreaName(mode)
                + " status=" + status);
        }
    }

    /** Recompute desiredCtx from connected/navActive and wake the worker. Caller must NOT hold LOCK. */
    private static void republish() {
        boolean ownCluster;
        synchronized (LOCK) {
            ownCluster = connected || videoAvailable;
            desiredCtx = !ownCluster ? CTX_STOCK_CLUSTER : (navActive ? CTX_CLUSTER : CTX_CLUSTER_MAP);
            LOCK.notifyAll();
        }
    }

    /** Data-plane fallback for transient/incorrect TMDev lifecycle events. */
    public static void setVideoAvailable(boolean available) {
        synchronized (LOCK) {
            if (!platformSupported) return;
            if (available && !connected && !acceptVideoFallback) {
                Log.d(TAG, "ignoring stale VIDEO_ON outside session/grace");
                return;
            }
            if (videoAvailable == available) return;
            videoAvailable = available;
        }
        Log.i(TAG, "videoAvailable=" + available + " connected=" + connected);
        republish();
    }

    /** Presentation latch, not merely route intent.  RouteGuidance may set true only after the
     *  current RGI delta has been published through BAP and maneuver_render has confirmed a frame.
     *  The stock KDK-visible hint never drives this latch. */
    public static void setNavActive(boolean active) {
        if (active) {
            boolean changed;
            synchronized (LOCK) {
                /* A fresh/current presentation wins over an old delayed hide. */
                navHideGeneration++;
                navHidePending = false;
                changed = !navActive;
                navActive = true;
            }
            if (!changed) return;
            Log.i(TAG, "RGI presentation=true -> ctx 80 (map+maneuver)");
            republish();
            return;
        }

        final int generation;
        synchronized (LOCK) {
            if (!navActive || navHidePending) return;
            navHidePending = true;
            generation = ++navHideGeneration;
        }
        Log.i(TAG, "RGI presentation=false -> holding ctx 80 for " + NAV_HIDE_HOLD_MS + "ms");
        Thread hide = new Thread(new Runnable() {
            public void run() {
                try { Thread.sleep(NAV_HIDE_HOLD_MS); }
                catch (InterruptedException e) { Thread.currentThread().interrupt(); return; }

                synchronized (LOCK) {
                    if (!navHidePending || generation != navHideGeneration || !navActive) return;
                    navHidePending = false;
                    navActive = false;
                }
                Log.i(TAG, "RGI hide hold complete -> ctx 81 (map only)");
                republish();
            }
        }, "carplay-rgi-hide-hold");
        hide.setDaemon(true);
        try {
            hide.start();
        } catch (Throwable t) {
            boolean changed = false;
            synchronized (LOCK) {
                if (navHidePending && generation == navHideGeneration && navActive) {
                    navHidePending = false;
                    navActive = false;
                    changed = true;
                }
            }
            Log.w(TAG, "RGI hide worker start failed; hiding immediately: " + t);
            if (changed) republish();
        }
    }

    /** The cluster-layer visibility gate read by CombiMapController.  It follows the confirmed BAP
     *  presentation, except for the intentional 250 ms removal hold, and never follows a stray stock
     *  KDK-visible bit. */
    public static boolean isNavActive() { return navActive; }

    public String name() { return "altscreen"; }

    public boolean start(FrameworkRef fw) {
        if (fw == null || !fw.isReady() || fw.framework() == null) return false;
        if (!isPlatformSupported(fw)) {
            platformSupported = false;
            enabled = false;
            Log.w(TAG, "disabled: G24 cluster has no ctx 80/81 altScreen composition");
            return true;
        }
        platformSupported = true;
        enabled = true;

        IDisplayManager d = null;
        try {
            if (fw.framework().getHMIService() != null) {
                d = fw.framework().getHMIService().getDisplayManager();
            }
        } catch (Throwable t) {
            Log.d(TAG, "getDisplayManager not ready: " + t);
        }
        if (d == null) return false;                 /* DM not up yet → retry */
        try {
            if (fw.framework().getLastmodeHandler() != null)
                layoutStorage = fw.framework().getLastmodeHandler().getLastmodeStorage();
        } catch (Throwable t) {
            Log.d(TAG, "stock VC skin storage not ready: " + t);
        }
        refreshClusterStyleFromStock("module-start");
        if (d instanceof IDisplayManagerKombiControl) {
            com.luka.carplay.cluster.ClusterLayerController.bind(
                (IDisplayManagerKombiControl)d, TERMINAL_CLUSTER);
        }
        CarplayBus bus = CarplayBus.getInstance();
        bus.on(CarplayBus.EVT_HELLO, this);
        bus.on(CarplayBus.CMD_ALT_ZONE_ACK, this);
        sendViewAreaMode("module-start");

        /* Publish the new session target before a new worker can observe currentCtx=-1. */
        synchronized (LOCK) {
            /* A replaced DisplayManager invalidates the cached currentCtx — reset so the worker
             * re-applies the desired ctx to the new one.  (In practice the same object each session.) */
            if (dm != d) { dm = d; currentCtx = -1; }
            connected = true;
            navActive = false;
            navHidePending = false;
            navHideGeneration++;
            acceptVideoFallback = true;
            lifecycleGeneration++;
            desiredCtx = CTX_CLUSTER_MAP;
        }
        synchronized (LOCK) {
            /* Create the single persistent worker once; recreate only if it never started or died.
             * Assign the field ONLY after start() succeeds so a throw leaves worker==null for retry. */
            if (worker == null || !worker.isAlive()) {
                Thread w = new Thread(new Runnable() { public void run() { switchLoop(); } }, "carplay-cluster-switch");
                w.setDaemon(true);
                w.start();
                worker = w;
            }
            LOCK.notifyAll();
        }
        Log.i(TAG, "ready (DisplayManager acquired, session reset -> ctx 81)");
        return true;
    }

    public void stop() {
        if (!enabled) return;
        enabled = false;
        /* Disconnect: publish stock (74); the single persistent worker restores it.  We deliberately
         * do NOT kill the worker or null dm — the worker being the sole always-live DM writer is what
         * makes stale-worker races impossible (no per-session worker to outlive its session). */
        final int generation;
        synchronized (LOCK) {
            connected = false;
            navActive = false;
            navHidePending = false;
            navHideGeneration++;
            acceptVideoFallback = true;
            generation = ++lifecycleGeneration;
        }
        republish();
        /* Bridge only short TMDev/dio bounces. A real disconnect must not leave a stale control
         * socket pinning plane 99 forever. A re-activate increments the generation and cancels this. */
        Thread grace = new Thread(new Runnable() {
            public void run() {
                try { Thread.sleep(VIDEO_FALLBACK_GRACE_MS); }
                catch (InterruptedException e) { Thread.currentThread().interrupt(); return; }
                boolean changed = false;
                synchronized (LOCK) {
                    if (generation == lifecycleGeneration && !connected) {
                        acceptVideoFallback = false;
                        if (videoAvailable) { videoAvailable = false; changed = true; }
                    }
                }
                if (changed) {
                    Log.i(TAG, "video fallback grace expired -> stock context");
                    republish();
                }
            }
        }, "carplay-video-grace");
        grace.setDaemon(true);
        grace.start();
        CarplayBus.getInstance().off(CarplayBus.EVT_HELLO);
        CarplayBus.getInstance().off(CarplayBus.CMD_ALT_ZONE_ACK);
    }

    /* ============================================================
     * Switch worker — the single serialized DM writer.
     * ============================================================ */

    private void switchLoop() {
        contextWriterThread = Thread.currentThread();
        while (true) {
            refreshClusterStyleFromStock("context-reconcile");
            int target; IDisplayManager d; boolean reconcileOnly = false;
            synchronized (LOCK) {
                while (dm == null) {
                    try { LOCK.wait(); } catch (InterruptedException e) { /* persistent worker */ }
                }
                if (desiredCtx == currentCtx) {
                    try {
                        if (desiredCtx == CTX_CLUSTER || desiredCtx == CTX_CLUSTER_MAP)
                            LOCK.wait(CONTEXT_RECONCILE_MS);
                        else
                            LOCK.wait();
                    } catch (InterruptedException e) { /* persistent worker */ }
                    if (dm == null || desiredCtx != currentCtx) continue;
                    if (desiredCtx != CTX_CLUSTER && desiredCtx != CTX_CLUSTER_MAP) continue;
                    reconcileOnly = true;
                }
                target = desiredCtx; d = dm;
            }
            if (reconcileOnly) {
                int actual;
                try { actual = d.getCurrentContextID(TERMINAL_CLUSTER); }
                catch (Throwable t) {
                    Log.w(TAG, "context reconcile read failed: " + t);
                    continue;
                }
                if (actual != target) {
                    boolean retry = false;
                    synchronized (LOCK) {
                        if (dm == d && desiredCtx == target && currentCtx == target) {
                            currentCtx = -1;
                            retry = true;
                            LOCK.notifyAll();
                        }
                    }
                    if (retry)
                        Log.w(TAG, "physical context drift actual=" + actual
                            + " desired=" + target + " -> reconcile");
                }
                continue;
            }
            applySwitch(target, d);
        }
    }

    /** Perform ONE context switch (bounce + settle + select).  Only this thread ever writes the DM,
     *  so there is no cross-worker race; the loop re-runs if desiredCtx changed during the settle.
     *  Note: a stop()/start() landing in the tiny window between the post-sleep recheck and the
     *  switchContext write can still cause ONE transient physical write before the next loop restores
     *  the newly-desired ctx — it is self-healing.  Closing it fully needs LOCK held across a DSI IPC
     *  call → deadlock risk, not worth it for a cosmetic transient on connect/disconnect. */
    private void applySwitch(int ctx, IDisplayManager d) {
        try {
            if (ctx != CTX_STOCK_CLUSTER) {
                int from;
                synchronized (LOCK) { from = currentCtx; }
                /* Bounce ONLY when the MOST encoder was off — i.e. we're coming from stock (74) or an
                 * unknown state (-1, after a DM replace / prior error).  switchContext short-circuits
                 * preContextSwitchHook + encoder re-point unless the ctx really changes, so the first
                 * grab of the cluster needs a real change via a throwaway ctx (72) + settle.
                 *
                 * Between our OWN contexts (80<->81) the encoder is already running on the cluster and
                 * both share plane 99 — a direct switchContext just recomposes the extra planes (98/101/
                 * 102), no re-point needed.  Skipping the bounce there removes the visible ~180ms flash
                 * through stock kombi-map (72) on every nav on/off.
                 * If the driver turns out to need the bounce even for 80<->81 (encoder judder),
                 * widen this back to "always bounce". */
                boolean encoderRunning = (from == CTX_CLUSTER || from == CTX_CLUSTER_MAP);
                if (!encoderRunning) {
                    int bounce = (ctx != CTX_BOUNCE) ? CTX_BOUNCE : CTX_STOCK_CLUSTER;
                    d.switchContext(bounce, TERMINAL_CLUSTER, null);
                    try { Thread.sleep(BOUNCE_SLEEP_MS); }
                    catch (InterruptedException ie) { Thread.currentThread().interrupt(); }
                    /* Coalesce: if the desired target or the DM changed during the settle, abandon THIS
                     * switch (cluster is on the bounce ctx) and let the loop apply the latest desired. */
                    synchronized (LOCK) {
                        if (dm != d || desiredCtx != ctx) {
                            currentCtx = -1;
                            Log.i(TAG, "switch(" + ctx + ") superseded during bounce → " + desiredCtx);
                            return;
                        }
                    }
                }
                d.switchContext(ctx, TERMINAL_CLUSTER, null);
                d.setUpdateRate(TERMINAL_CLUSTER, CLUSTER_FPS);   /* (idempotent when already running) */
                clusterActive = true;                             /* roller → CMD_ALT_ZOOM */
            } else {
                /* Preserve the stop-before-switch ordering, but never leave terminal 1
                 * parked at 0 FPS. On this A5/MHI2Q the stock
                 * KOMBI_KDK_VIA_DISPLAYABLES branch bypasses CombiMapController's
                 * optional 10/1/0 updateFrameRate() path, so 10 is not an authoritative
                 * restore value here. Return the terminal to the same full 30 Hz rate
                 * used by the live cluster encoder; stock may change it later if it has
                 * an applicable producer. */
                d.setUpdateRate(TERMINAL_CLUSTER, 0);
                try {
                    d.switchContext(CTX_STOCK_CLUSTER, TERMINAL_CLUSTER, null);
                } finally {
                    d.setUpdateRate(TERMINAL_CLUSTER, CLUSTER_FPS);
                }
                clusterActive = false;
            }
            synchronized (LOCK) { if (dm == d) currentCtx = ctx; }
            /* Context composition is now final: replay the last KDK popup/sport geometry so a
             * navActive edge cannot leave planes 98/101/102 at their previous opacity. */
            com.luka.carplay.cluster.ClusterLayerController.reapply();
            Log.i(TAG, "cluster -> ctx " + ctx + " (active=" + clusterActive + ")");
        } catch (Throwable t) {
            Log.w(TAG, "switch(" + ctx + ") failed: " + t);
            synchronized (LOCK) { currentCtx = -1; }
            /* Throttle the retry: the bounce write and the stock path have no settle sleep, so a
             * persistently-throwing switchContext would otherwise hot-spin (busy loop + log flood). */
            try { Thread.sleep(BOUNCE_SLEEP_MS); } catch (InterruptedException ie) { Thread.currentThread().interrupt(); }
        }
    }
}
