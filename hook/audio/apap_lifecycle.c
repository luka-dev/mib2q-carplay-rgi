/* See apap_lifecycle.h. */
#include "apap_lifecycle.h"

#include <stdlib.h>
#include <string.h>

struct spa_apap_queued_packet {
    struct spa_apap_queued_packet *next;
    size_t length;
    uint32_t sequence;
    uint32_t rtp;
    uint8_t bytes[1];
};

static int counter_after(uint32_t value, uint32_t boundary,
                         uint32_t mask, uint32_t half)
{
    uint32_t delta = (value - boundary) & mask;
    return delta != 0 && delta < half;
}

static int counter_in_interval(uint32_t value, uint32_t from,
                               uint32_t until, uint32_t mask,
                               uint32_t half)
{
    uint32_t span = (until - from) & mask;
    uint32_t delta = (value - from) & mask;

    /* Ambiguous ranges spanning half or more of a wrapping counter are not
     * generated by AirPlay.  Fail closed to the ordinary signed comparisons
     * instead of turning a malformed request into an almost-global delete. */
    if (span >= half)
        return (value == from || counter_after(value, from, mask, half)) &&
               (value == until || !counter_after(value, until, mask, half));
    return delta <= span;
}

static int counter_matches(uint32_t value,
                           int have_from, uint32_t from,
                           int have_until, uint32_t until,
                           uint32_t mask, uint32_t half)
{
    value &= mask;
    from &= mask;
    until &= mask;
    if (have_from && have_until)
        return counter_in_interval(value, from, until, mask, half);
    if (have_from)
        return value == from || counter_after(value, from, mask, half);
    if (have_until)
        return value == until || !counter_after(value, until, mask, half);
    return 1;
}

static void free_packet(spa_apap_queued_packet_t *packet)
{
    free(packet);
}

void spa_apap_lifecycle_init(spa_apap_lifecycle_t *state,
                             size_t byte_limit)
{
    if (!state) return;
    memset(state, 0, sizeof(*state));
    state->byte_limit = byte_limit;
    /* SETUP constructs a stopped queue.  Only SETRATE{rate=1} presents it. */
    state->playing = 0;
}

void spa_apap_lifecycle_dispose(spa_apap_lifecycle_t *state)
{
    spa_apap_queued_packet_t *packet;

    if (!state) return;
    packet = state->head;
    while (packet) {
        spa_apap_queued_packet_t *next = packet->next;
        free_packet(packet);
        packet = next;
    }
    free_packet(state->inflight);
    memset(state, 0, sizeof(*state));
}

void spa_apap_lifecycle_set_rate(spa_apap_lifecycle_t *state,
                                 int64_t rate)
{
    if (state) state->playing = rate == 1;
}

int spa_apap_lifecycle_playing(const spa_apap_lifecycle_t *state)
{
    return state && state->playing;
}

int spa_apap_lifecycle_saturated(const spa_apap_lifecycle_t *state)
{
    return state && state->byte_limit != 0 &&
           state->queued_bytes >= state->byte_limit;
}

int spa_apap_flush_range_contains(const spa_apap_flush_range_t *range,
                                  uint32_t sequence, uint32_t rtp)
{
    int sequence_match;
    int rtp_match;

    if (!range) return 0;
    sequence_match = counter_matches(
        sequence, range->have_from_sequence, range->from_sequence,
        range->have_until_sequence, range->until_sequence,
        UINT32_C(0x00ffffff), UINT32_C(0x00800000));
    rtp_match = counter_matches(
        rtp, range->have_from_rtp, range->from_rtp,
        range->have_until_rtp, range->until_rtp,
        UINT32_MAX, UINT32_C(0x80000000));
    return sequence_match && rtp_match;
}

int spa_apap_flush_range_after_upper(const spa_apap_flush_range_t *range,
                                     uint32_t sequence, uint32_t rtp)
{
    if (!range) return 0;
    if (range->have_until_sequence)
        return counter_after(sequence & UINT32_C(0x00ffffff),
                             range->until_sequence & UINT32_C(0x00ffffff),
                             UINT32_C(0x00ffffff), UINT32_C(0x00800000));
    if (range->have_until_rtp)
        return counter_after(rtp, range->until_rtp,
                             UINT32_MAX, UINT32_C(0x80000000));
    return 0;
}

int spa_apap_lifecycle_observe(spa_apap_lifecycle_t *state,
                               uint32_t sequence, uint32_t rtp,
                               int *crossed_upper)
{
    if (crossed_upper) *crossed_upper = 0;
    if (!state || !state->flush_pending) return 0;
    if (spa_apap_flush_range_contains(&state->flush, sequence, rtp)) {
        if (state->inflight_discard && state->inflight &&
            state->inflight->sequence ==
                (sequence & UINT32_C(0x00ffffff)) &&
            state->inflight->rtp == rtp)
            return 1;
        state->current_flush_dropped++;
        state->total_flush_dropped++;
        return 1;
    }
    if (spa_apap_flush_range_after_upper(&state->flush, sequence, rtp)) {
        state->flush_pending = 0;
        if (crossed_upper) *crossed_upper = 1;
    }
    return 0;
}

int spa_apap_lifecycle_enqueue(spa_apap_lifecycle_t *state,
                               const uint8_t *bytes, size_t length,
                               uint32_t sequence, uint32_t rtp,
                               int *crossed_upper)
{
    spa_apap_queued_packet_t *packet;

    if (!state || !bytes || !length) return SPA_APAP_ENQUEUE_NO_MEMORY;
    if (spa_apap_lifecycle_observe(state, sequence, rtp, crossed_upper))
        return SPA_APAP_ENQUEUE_DROPPED_FLUSH;
    /* The receiver stops reading as soon as it reaches the advertised limit.
     * Accept the record which crosses it so a complete APAP record is never
     * lost; memory is bounded by limit + one maximum record. */
    if (state->byte_limit && state->queued_bytes >= state->byte_limit)
        return SPA_APAP_ENQUEUE_FULL;
    if (length > SIZE_MAX - sizeof(*packet)) {
        state->allocation_failures++;
        return SPA_APAP_ENQUEUE_NO_MEMORY;
    }
    packet = (spa_apap_queued_packet_t *)malloc(
        sizeof(*packet) - sizeof(packet->bytes) + length);
    if (!packet) {
        state->allocation_failures++;
        return SPA_APAP_ENQUEUE_NO_MEMORY;
    }
    packet->next = 0;
    packet->length = length;
    packet->sequence = sequence & UINT32_C(0x00ffffff);
    packet->rtp = rtp;
    memcpy(packet->bytes, bytes, length);
    if (state->tail)
        state->tail->next = packet;
    else
        state->head = packet;
    state->tail = packet;
    state->queued_bytes += length;
    state->queued_packets++;
    return SPA_APAP_ENQUEUE_QUEUED;
}

const uint8_t *spa_apap_lifecycle_take(spa_apap_lifecycle_t *state,
                                       size_t *length,
                                       uint32_t *sequence,
                                       uint32_t *rtp)
{
    spa_apap_queued_packet_t *packet;

    if (!state || !state->playing || state->inflight || !state->head)
        return 0;
    packet = state->head;
    state->head = packet->next;
    if (!state->head) state->tail = 0;
    packet->next = 0;
    state->queued_bytes -= packet->length;
    state->queued_packets--;
    state->inflight = packet;
    state->inflight_discard = 0;
    if (length) *length = packet->length;
    if (sequence) *sequence = packet->sequence;
    if (rtp) *rtp = packet->rtp;
    return packet->bytes;
}

void spa_apap_lifecycle_finish(spa_apap_lifecycle_t *state,
                               int requeue_front)
{
    spa_apap_queued_packet_t *packet;

    if (!state || !state->inflight) return;
    packet = state->inflight;
    state->inflight = 0;
    if (requeue_front && !state->inflight_discard) {
        packet->next = state->head;
        state->head = packet;
        if (!state->tail) state->tail = packet;
        state->queued_bytes += packet->length;
        state->queued_packets++;
    } else {
        free_packet(packet);
    }
    state->inflight_discard = 0;
}

void spa_apap_lifecycle_begin_flush(spa_apap_lifecycle_t *state,
                                    const spa_apap_flush_range_t *range,
                                    size_t *removed_packets,
                                    size_t *removed_bytes)
{
    spa_apap_queued_packet_t *packet;
    spa_apap_queued_packet_t *previous = 0;
    size_t packet_count = 0;
    size_t byte_count = 0;

    if (removed_packets) *removed_packets = 0;
    if (removed_bytes) *removed_bytes = 0;
    if (!state || !range) return;

    state->flush = *range;
    state->flush.from_sequence &= UINT32_C(0x00ffffff);
    state->flush.until_sequence &= UINT32_C(0x00ffffff);
    /* Only an upper boundary can classify future arrivals and tell us when
     * rejection is complete.  A from-only request prunes the queue as it
     * exists now; arming an endless future suffix would permanently mute the
     * stream after one malformed/legacy request. */
    state->flush_pending = range->have_until_sequence ||
                           range->have_until_rtp;
    state->current_flush_dropped = 0;

    packet = state->head;
    while (packet) {
        spa_apap_queued_packet_t *next = packet->next;
        if (spa_apap_flush_range_contains(&state->flush,
                                          packet->sequence, packet->rtp)) {
            if (previous)
                previous->next = next;
            else
                state->head = next;
            if (state->tail == packet) state->tail = previous;
            state->queued_bytes -= packet->length;
            state->queued_packets--;
            byte_count += packet->length;
            packet_count++;
            free_packet(packet);
        } else {
            previous = packet;
        }
        packet = next;
    }
    if (state->inflight &&
        spa_apap_flush_range_contains(&state->flush,
                                      state->inflight->sequence,
                                      state->inflight->rtp)) {
        state->inflight_discard = 1;
        packet_count++;
        byte_count += state->inflight->length;
    }
    state->current_flush_dropped += packet_count;
    state->total_flush_dropped += packet_count;
    if (removed_packets) *removed_packets = packet_count;
    if (removed_bytes) *removed_bytes = byte_count;
}
